/**
 * The CSS and TypeScript emitters.
 *
 * All of them share one behaviour that is easy to miss and load-bearing: a
 * token whose authored value is a reference is emitted as `var(--other-token)`,
 * never as the resolved literal. That is what keeps the layers *live* — flip
 * `data-theme` and a component token re-resolves through the cascade on its
 * own, with no duplicated blocks and no JavaScript.
 */
import { ROOTS, AXES, DEFAULTS, selectorFor } from "./axes.mjs";
import {
  cssVar,
  refsToVars,
  hasRef,
  semanticKey,
  tokenName,
} from "./naming.mjs";

/** Key for the axis-free slice in the inspector graph. Not a legal axis value. */
export const DEFAULT_SLICE = "*";

const BANNER = (note) =>
  [
    "/**",
    " * GENERATED by `yarn tokens` from the JSON under tokens/ — do not edit.",
    ` * ${note}`,
    " */",
    "",
  ].join("\n");

/** `--name: value;` for one token, preserving references as `var()`. */
function declaration(token) {
  const authored = token.original?.$value ?? token.$value;
  const value = hasRef(authored) ? refsToVars(authored) : token.$value;
  return `  ${cssVar(token.path)}: ${value};`;
}

/** Declarations for a token list, grouped by their second-to-last path segment. */
function body(tokens, axisDepth) {
  const groups = new Map();
  for (const token of tokens) {
    const key = token.path.slice(1 + axisDepth, -1).join(".") || "·";
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(token);
  }
  const out = [];
  for (const [group, items] of groups) {
    if (group !== "·") out.push(`\n  /* ${group} */`);
    out.push(...items.map(declaration));
  }
  return out.join("\n");
}

/** One plain block under a fixed selector. Used for `prim.*`, `sem.*`, `cmp.*`. */
export const cssBlock = ({ dictionary, options }) => {
  const tokens = dictionary.allTokens;
  if (!tokens.length) return "";
  const selector = options.selector ?? ":root";
  return `${BANNER(options.note ?? "")}${selector} {\n${body(tokens, 0)}\n}\n`;
};

/**
 * One block per axis combination, with the selector derived from the axis
 * manifest. The *same* variable names appear in every block — that is the whole
 * trick, and why 24 colour worlds cost 24 short blocks instead of a cartesian
 * product of every token.
 */
export const cssAxisBlocks = ({ dictionary, options }) => {
  const root = options.root;
  const { axisDepth, axes } = ROOTS[root];
  const blocks = new Map();
  for (const token of dictionary.allTokens) {
    const coords = token.path.slice(1, 1 + axisDepth);
    const key = coords.join("/");
    if (!blocks.has(key)) blocks.set(key, { coords, tokens: [] });
    blocks.get(key).tokens.push(token);
  }
  const chunks = [];
  for (const { coords, tokens } of blocks.values()) {
    const label = coords.map((value, i) => `${axes[i]}: ${value}`).join(", ");
    chunks.push(
      `/* ${label} */\n${selectorFor(root, coords)} {\n${body(tokens, axisDepth)}\n}`
    );
  }
  return `${BANNER(options.note ?? "")}${chunks.join("\n\n")}\n`;
};

/**
 * Semantic name → Tailwind theme variable. The `inline` keyword on the emitted
 * `@theme` block is load-bearing: it makes Tailwind's generated utilities emit
 * `var(--sem-*)` rather than baking the value in at build time, which is the
 * only reason `bg-surface-base` keeps tracking a runtime axis flip.
 */
const TAILWIND_MAP = [
  [/^(surface|content|border|accent|action)-/, (key) => `--color-${key}`],
  [/^focus-ring$/, (key) => `--color-${key}`],
  [/^space-(.+)$/, (_key, m) => `--spacing-${m[1]}`],
  [/^(control|block)-/, (key) => `--spacing-${key}`],
  [/^radius-(.+)$/, (_key, m) => `--radius-${m[1]}`],
  [/^shadow-(.+)$/, (_key, m) => `--shadow-${m[1]}`],
  [/^font-(.+)$/, (_key, m) => `--font-${m[1]}`],
  [/^weight-(.+)$/, (_key, m) => `--font-weight-${m[1]}`],
  [/^tracking-(.+)$/, (_key, m) => `--tracking-${m[1]}`],
  [/^measure-(.+)$/, (_key, m) => `--container-${m[1]}`],
  [/^material-blur$/, () => "--blur-surface"],
  [/^motion-ease-(.+)$/, (_key, m) => `--ease-${m[1]}`],
  // The type ramp: one semantic token per Tailwind text-size sub-property, so a
  // single `text-h1` carries size, leading, weight and tracking.
  [/^text-(.+)-size$/, (_key, m) => `--text-${m[1]}`],
  [/^text-(.+)-leading$/, (_key, m) => `--text-${m[1]}--line-height`],
  [/^text-(.+)-weight$/, (_key, m) => `--text-${m[1]}--font-weight`],
  [/^text-(.+)-tracking$/, (_key, m) => `--text-${m[1]}--letter-spacing`],
];

export function tailwindVarFor(key) {
  for (const [test, build] of TAILWIND_MAP) {
    const match = key.match(test);
    if (match) return build(key, match);
  }
  return null;
}

/**
 * The `@theme inline` block — generated off the canonical semantic slice, so
 * adding a semantic token automatically yields a Tailwind utility and the two
 * can never drift. The token name *is* the class name; there is no mapping
 * layer to keep in sync.
 */
export const cssThemeInline = ({ dictionary, options }) => {
  const mapped = [];
  const unmapped = [];
  for (const token of dictionary.allTokens) {
    const key = semanticKey(tokenName(token.path));
    const target = tailwindVarFor(key);
    if (target) mapped.push([target, cssVar(token.path)]);
    else unmapped.push(key);
  }
  mapped.sort((a, b) => a[0].localeCompare(b[0]));
  const width = Math.max(...mapped.map(([name]) => name.length)) + 1;
  const lines = mapped.map(
    ([name, source]) => `  ${(name + ":").padEnd(width)} var(${source});`
  );

  const note = unmapped.length
    ? [
        "",
        "/*",
        " * Semantic tokens with no Tailwind namespace to map onto. They are still",
        " * real custom properties and still follow every axis — reach for them with",
        " * an arbitrary value, e.g. `duration-[var(--sem-motion-duration-fast)]`:",
        ...unmapped.sort().map((key) => ` *   --sem-${key}`),
        " */",
      ].join("\n")
    : "";

  return `${BANNER(options.note ?? "")}@theme inline {\n${lines.join("\n")}\n}\n${note}\n`;
};

/**
 * The reference graph the token inspector reads.
 *
 * The CSS emitters above throw away everything except names and values, which
 * is right for the browser and useless for a page whose job is to *explain* the
 * system. This one keeps the other half: which layer a token lives in, which
 * axes it varies on, and the authored `{reference}` for every axis slice — so
 * the inspector can walk component → semantic → primitive without re-reading
 * the JSON at runtime.
 *
 * Resolved *values* are deliberately absent: the inspector reads those off
 * `getComputedStyle(document.documentElement)`, which means what it shows is
 * what the browser actually computed, not what this build predicted.
 */
export const jsonGraph = ({ dictionary, options }) => {
  const nodes = {};
  for (const token of dictionary.allTokens) {
    const root = ROOTS[token.path[0]];
    if (!root) continue;
    const name = tokenName(token.path);
    const coords = token.path.slice(1, 1 + root.axisDepth);
    const authored = String(token.original?.$value ?? token.$value);

    const node = (nodes[name] ??= {
      layer: root.layer,
      type: token.$type ?? null,
      group: token.path.slice(1 + root.axisDepth, -1).join("-") || null,
      tailwind:
        root.layer === "semantic" ? tailwindVarFor(semanticKey(name)) : null,
      varies: [],
      values: {},
    });

    /**
     * `varies` is unioned across roots on purpose: the theme axis reaches a
     * semantic token through `semColor` *and* `semExpr`, and a reader of the
     * inspector wants "this follows theme", not two half-answers.
     */
    for (const axis of root.axes ?? []) {
      if (!node.varies.includes(axis)) node.varies.push(axis);
    }
    node.values[coords.join(".") || DEFAULT_SLICE] = authored;
  }

  const sorted = Object.fromEntries(
    Object.entries(nodes).sort(([a], [b]) => a.localeCompare(b))
  );
  return `${JSON.stringify(
    {
      note: options.note ?? "",
      slices: { default: DEFAULT_SLICE },
      nodes: sorted,
    },
    null,
    2
  )}\n`;
};

/** Typed names, axis types and the theme manifest a switcher UI needs. */
export const tsManifest = ({ dictionary, options }) => {
  const names = { semantic: [], component: [], primitive: [] };
  for (const token of dictionary.allTokens) {
    const layer = ROOTS[token.path[0]]?.layer;
    if (layer === "semantic" && token.path[0] !== "sem") continue; // axis variants share a name
    if (layer) names[layer].push(tokenName(token.path));
  }
  const list = (items) =>
    `[\n${[...new Set(items)]
      .sort()
      .map((n) => `  "${n}",`)
      .join("\n")}\n] as const`;

  const themes = AXES.theme.values.map((id) => ({
    id,
    description: options.themeDescriptions[id] ?? "",
  }));

  return `/**
 * GENERATED by \`yarn tokens\` — do not edit.
 *
 * The axis manifest and the full token vocabulary, as types. The theme switcher
 * built in a later phase reads this, so the control and the CSS cannot drift:
 * adding a theme to \`tokens/lib/axes.mjs\` changes this file, and anything
 * switching on \`Theme\` stops compiling until it handles the new one.
 */

export const AXES = ${JSON.stringify(AXES, null, 2)} as const;

export const AXIS_DEFAULTS = ${JSON.stringify(DEFAULTS, null, 2)} as const;

export type Theme = (typeof AXES)["theme"]["values"][number];
export type Appearance = (typeof AXES)["appearance"]["values"][number];
export type Density = (typeof AXES)["density"]["values"][number];
export type Contrast = (typeof AXES)["contrast"]["values"][number];

export type AxisSelection = {
  theme: Theme;
  appearance: Appearance;
  density: Density;
  contrast: Contrast;
};

/** The six themes, in display order. */
export const THEMES = ${JSON.stringify(themes, null, 2)} as const;

/** \`data-*\` attributes for one selection, ready to spread onto \`<html>\`. */
export function axisAttributes(selection: AxisSelection) {
  return {
    "data-theme": selection.theme,
    "data-appearance": selection.appearance,
    "data-density": selection.density,
    "data-contrast": selection.contrast,
  } as const;
}

/** Every semantic token name. Identical in all ${AXES.theme.values.length} themes — that is the contract. */
export const SEMANTIC_TOKENS = ${list(names.semantic)};
export type SemanticToken = (typeof SEMANTIC_TOKENS)[number];

/** Every component token name. These resolve through the semantic layer. */
export const COMPONENT_TOKENS = ${list(names.component)};
export type ComponentToken = (typeof COMPONENT_TOKENS)[number];

/** Every primitive token name. Not for consumption — listed for the inspector. */
export const PRIMITIVE_TOKENS = ${list(names.primitive)};
export type PrimitiveToken = (typeof PRIMITIVE_TOKENS)[number];

export const cssVar = (token: SemanticToken | ComponentToken | PrimitiveToken) =>
  \`var(--\${token})\`;
`;
};
